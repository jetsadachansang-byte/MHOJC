def elem_line(s):
    m=re.match(r'^(Fire|Water|Thunder|Ice|Dragon) damage \+(\d+)%; (?:against Radiant monsters, \w+ damage \+(\d+)% instead|\+(\d+)% instead against Radiant monsters)\.?$',s)
    if m:e=EL[m.group(1)];return f"ดาเมจธาตุ{e} +{m.group(2)}% (ต่อมอนสเตอร์ Radiant +{m.group(3) or m.group(4)}%)"
    m=re.match(r'^(Fire|Water|Thunder|Ice|Dragon) attack \+(\d+)[;,] \w+ damage \+(\d+)%; (?:against Radiant monsters, \w+ damage \+(\d+)% instead|\+(\d+)% instead against Radiant monsters)\.?$',s)
    if m:e=EL[m.group(1)];return f"ค่าธาตุ{e} +{m.group(2)}, ดาเมจธาตุ{e} +{m.group(3)}% (ต่อมอนสเตอร์ Radiant +{m.group(4) or m.group(5)}%)"
    m=re.match(r'^(Fire|Water|Thunder|Ice|Dragon) resistance \+(\d+)\.?$',s,re.I)
    if m:return f"ต้านทานธาตุ{EL[m.group(1).capitalize()]} +{m.group(2)}"
    return None
def one(s):
    s=s.strip()
    if not s:return ''
    r=elem_line(s)
    if r:return r
    k=re.sub(r'\d+(\.\d+)?','#',s)
    if not k.endswith('.') and k+'.' in T:k+='.'
    if k in T:
        nums=re.findall(r'\d+(?:\.\d+)?',s);return T[k].format(*nums)
    return None
def tr(s):
    r=one(s)
    if r is not None:return r
    # split into sentences
    parts=re.split(r'(?<=\.) (?=[A-Z])',s)
    if len(parts)>1:
        out=[one(p) for p in parts]
        if all(o is not None for o in out):return ' · '.join(out)
    raise KeyError(s)
